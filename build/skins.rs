use serde::Deserialize;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Deserialize, Default)]
struct SkinManifestRaw {
    id: Option<String>,
    component: Option<String>,
    file: Option<String>,
    width: Option<String>,
    height: Option<String>,
    border_radius: Option<String>,
    border_top_left_radius: Option<String>,
    border_top_right_radius: Option<String>,
    border_bottom_left_radius: Option<String>,
    border_bottom_right_radius: Option<String>,
    transparent_background: Option<bool>,
}

pub struct SkinEntry {
    pub id: String,
    pub component: String,
    pub rel_file_path: String,
    pub width: String,
    pub height: String,
    pub border_radius: String,
    pub border_top_left_radius: String,
    pub border_top_right_radius: String,
    pub border_bottom_left_radius: String,
    pub border_bottom_right_radius: String,
    pub transparent_background: bool,
}

fn to_pascal_case(s: &str) -> String {
    s.split(['-', '_'])
        .filter(|part| !part.is_empty())
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

pub fn discover_skins(skins_dir: &Path) -> Result<Vec<SkinEntry>, Box<dyn Error>> {
    let mut skins = Vec::new();
    if !skins_dir.exists() {
        return Ok(skins);
    }

    for entry in fs::read_dir(skins_dir)? {
        let entry = entry?;
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }

        let dir_name = match path.file_name().and_then(|n| n.to_str()) {
            Some(name) => name.to_string(),
            None => continue,
        };

        let manifest_path = path.join("skin.toml");
        let raw = if manifest_path.exists() {
            let content = fs::read_to_string(&manifest_path)?;
            toml::from_str::<SkinManifestRaw>(&content)?
        } else {
            SkinManifestRaw::default()
        };

        let id = raw.id.unwrap_or_else(|| dir_name.clone());
        let component = raw.component.unwrap_or_else(|| to_pascal_case(&id));
        let file_name = raw.file.unwrap_or_else(|| format!("{dir_name}.slint"));
        let slint_file = path.join(&file_name);

        if !slint_file.exists() {
            continue;
        }

        let default_zero = "0px".to_string();
        skins.push(SkinEntry {
            id,
            component,
            rel_file_path: format!("{dir_name}/{file_name}"),
            width: raw.width.unwrap_or_else(|| "200px".into()),
            height: raw.height.unwrap_or_else(|| "200px".into()),
            border_radius: raw.border_radius.unwrap_or_else(|| default_zero.clone()),
            border_top_left_radius: raw.border_top_left_radius.unwrap_or_else(|| default_zero.clone()),
            border_top_right_radius: raw.border_top_right_radius.unwrap_or_else(|| default_zero.clone()),
            border_bottom_left_radius: raw.border_bottom_left_radius.unwrap_or_else(|| default_zero.clone()),
            border_bottom_right_radius: raw.border_bottom_right_radius.unwrap_or(default_zero),
            transparent_background: raw.transparent_background.unwrap_or(false),
        });
    }

    skins.sort_by(|a, b| a.id.cmp(&b.id));
    Ok(skins)
}

pub fn generate() -> Result<(), Box<dyn Error>> {
    let skins_dir = PathBuf::from("ui/skins");
    let output_file = skins_dir.join("generated_skins.slint");
    let skins = discover_skins(&skins_dir)?;

    let mut out = String::new();
    out.push_str(
        "// =============================================================================\n\
         // THIS FILE IS AUTOMATICALLY GENERATED BY `build/skins.rs`.\n\
         // DO NOT EDIT THIS FILE MANUALLY!\n\
         //\n\
         // Source of truth: `ui/skins/*/skin.toml` and skin component files.\n\
         // Any manual changes made to this file will be overwritten on the next build.\n\
         // =============================================================================\n\n",
    );

    out.push_str("import { BaseSkin } from \"base-skin.slint\";\n");
    for skin in &skins {
        out.push_str(&format!(
            "import {{ {} }} from \"{}\";\n",
            skin.component, skin.rel_file_path
        ));
    }
    out.push('\n');

    out.push_str(
        "export struct SkinConfig {\n\
             width: length,\n\
             height: length,\n\
             border_radius: length,\n\
             border_top_left_radius: length,\n\
             border_top_right_radius: length,\n\
             border_bottom_left_radius: length,\n\
             border_bottom_right_radius: length,\n\
             transparent_background: bool,\n\
         }\n\n",
    );

    out.push_str(
        "export global SkinRegistry {\n\
             pure public function get_config(skin_name: string) -> SkinConfig {\n",
    );
    for skin in &skins {
        out.push_str(&format!(
            "        if (skin_name.to-lowercase() == \"{}\") {{\n\
                         return {{\n\
                             width: {},\n\
                             height: {},\n\
                             border_radius: {},\n\
                             border_top_left_radius: {},\n\
                             border_top_right_radius: {},\n\
                             border_bottom_left_radius: {},\n\
                             border_bottom_right_radius: {},\n\
                             transparent_background: {},\n\
                         }};\n\
                     }}\n",
            skin.id.to_lowercase(),
            skin.width,
            skin.height,
            skin.border_radius,
            skin.border_top_left_radius,
            skin.border_top_right_radius,
            skin.border_bottom_left_radius,
            skin.border_bottom_right_radius,
            skin.transparent_background,
        ));
    }
    out.push_str(
        "        return {\n\
                     width: 200px,\n\
                     height: 200px,\n\
                     border_radius: 0px,\n\
                     border_top_left_radius: 0px,\n\
                     border_top_right_radius: 0px,\n\
                     border_bottom_left_radius: 0px,\n\
                     border_bottom_right_radius: 0px,\n\
                     transparent_background: false,\n\
                 };\n\
             }\n\
         }\n\n",
    );

    out.push_str(
        "export component SkinHost inherits BaseSkin {\n\
             in property <string> skin;\n\n",
    );
    for skin in &skins {
        out.push_str(&format!(
            "    if (root.skin.to-lowercase() == \"{}\"): {} {{\n\
                     media_data: root.media_data;\n\
                     position_secs: root.position_secs;\n\
                     animation_state: root.animation_state;\n\
                     play_pause => {{ root.play_pause() }}\n\
                     next => {{ root.next() }}\n\
                     prev => {{ root.prev() }}\n\
                     seek(val) => {{ root.seek(val) }}\n\
                     visualizer_toggled(active) => {{ root.visualizer_toggled(active) }}\n\
                 }}\n",
            skin.id.to_lowercase(),
            skin.component,
        ));
    }
    out.push_str("}\n");

    if let Ok(existing) = fs::read_to_string(&output_file)
        && existing == out
    {
        return Ok(());
    }

    fs::write(output_file, out)?;
    Ok(())
}
